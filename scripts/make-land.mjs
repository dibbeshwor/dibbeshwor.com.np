/**
 * Rasterises a land GeoJSON (Natural Earth 110m works well) into a 360×180
 * one-bit mask and writes it, base64-packed, to src/lib/cosmos/land.ts.
 *
 *   node scripts/make-land.mjs path/to/ne_110m_land.geojson
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [, , src] = process.argv
if (!src) { console.error('usage: node scripts/make-land.mjs <land.geojson>'); process.exit(1) }
const W = 360, H = 180
const gj = JSON.parse(readFileSync(src, 'utf8'))
const rings = []
for (const f of gj.features) {
  const g = f.geometry
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : []
  for (const poly of polys) rings.push(poly) // [outer, ...holes]
}
function inside(poly, x, y) {
  let c = false
  for (const ring of poly) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i], [xj, yj] = ring[j]
      if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
    }
  }
  return c
}
const bits = new Uint8Array((W * H) / 8)
let land = 0
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) * (180 / H)
  for (let col = 0; col < W; col++) {
    const lon = -180 + (col + 0.5) * (360 / W)
    let on = false
    for (const poly of rings) { if (inside(poly, lon, lat)) { on = true; break } }
    if (on) { const i = r * W + col; bits[i >> 3] |= 1 << (i & 7); land++ }
  }
}
const b64 = Buffer.from(bits).toString('base64')
const out = `/**
 * 360×180 one-bit land mask (Natural Earth 110m), row 0 = 90°N, column 0 = 180°W.
 * Generated by scripts/make-land.mjs; do not edit by hand.
 */
const W = ${W}, H = ${H}
let bits: Uint8Array | null = null
function decode() {
  const s = atob(LAND)
  const b = new Uint8Array(s.length)
  for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i)
  return b
}
/** true when the point is on land. lat in degrees north, lon in degrees east. */
export function isLand(lat: number, lon: number) {
  if (!bits) bits = decode()
  const r = Math.min(H - 1, Math.max(0, Math.floor((90 - lat) / (180 / H))))
  const c = ((Math.floor((lon + 180) / (360 / W)) % W) + W) % W
  const i = r * W + c
  return (bits[i >> 3] & (1 << (i & 7))) !== 0
}
const LAND =
  '${b64}'
`
writeFileSync(new URL('../src/lib/cosmos/land.ts', import.meta.url), out)
console.log(`land cells: ${land} / ${W * H} (${((100 * land) / (W * H)).toFixed(1)}%), ${b64.length} chars`)
